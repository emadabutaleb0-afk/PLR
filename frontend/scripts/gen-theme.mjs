// Generates app/theme.css: CSS-variable colour scales for light and dark mode, and checks WCAG contrast of the pairs the UI really uses.
// Run:  node scripts/gen-theme.mjs   (rewrites app/theme.css; exits 1 if a checked pair falls below its minimum contrast)
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const colors = require("tailwindcss/colors");

const hex2rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgb2hex = (r) => "#" + r.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
const blend = (fg, bg, a) => fg.map((v, i) => v * a + bg[i] * (1 - a));
const lum = (c) => { const f = c.map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }); return 0.2126 * f[0] + 0.7152 * f[1] + 0.0722 * f[2]; };
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

// ---- semantic surfaces (RGB) - Modern Obsidian & Royal Indigo (Linear theme)
const S = {
  light: { canvas: "#F8FAFC", surface: "#FFFFFF", raised: "#FFFFFF", sunken: "#F1F5F9", line: "#E2E8F0", "line-strong": "#CBD5E1", accent: "#4F46E5", "accent-hover": "#4338CA", "accent-fg": "#FFFFFF", focus: "#6366F1" },
  dark: { canvas: "#0B0F19", surface: "#111827", raised: "#1F2937", sunken: "#080C14", line: "#1F2937", "line-strong": "#374151", accent: "#5850EC", "accent-hover": "#818CF8", "accent-fg": "#FFFFFF", focus: "#818CF8" },
};
const slateDark = { 50: "#111827", 100: "#172033", 200: "#1F2937", 300: "#374151", 400: "#9CA3AF", 500: "#D1D5DB", 600: "#E5E7EB", 700: "#F3F4F6", 800: "#F9FAFB", 900: "#FFFFFF", 950: "#FFFFFF" };
const royalIndigo = { 50: "#EEF2FF", 100: "#E0E7FF", 200: "#C7D2FE", 300: "#A5B4FC", 400: "#818CF8", 500: "#6366F1", 600: "#4F46E5", 700: "#4338CA", 800: "#3730A3", 900: "#312E81" };
const royalIndigoDark = { 400: "#818CF8", 500: "#6366F1", 600: "#A5B4FC", 700: "#C7D2FE", 800: "#E0E7FF", 900: "#EEF2FF" };
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900];
const surfDark = hex2rgb(S.dark.surface);
const lightShift = { emerald: { 600: 700 }, amber: { 600: 700 }, orange: { 600: 700 }, sky: { 600: 700 }, brand: { 600: 700 } };

const scales = {}; // name -> {light:{shade:rgb}, dark:{shade:rgb}}
for (const n of ["emerald", "rose", "amber", "orange", "sky", "violet"]) {
  const base = colors[n]; const L = {}, D = {};
  for (const s of SHADES) L[s] = hex2rgb(base[lightShift[n]?.[s] ? lightShift[n][s] : s]);
  const alpha = { 50: 0.1, 100: 0.16, 200: 0.26, 300: 0.4 };
  for (const s of [50, 100, 200, 300]) D[s] = blend(hex2rgb(base[500]), surfDark, alpha[s]);
  D[400] = hex2rgb(base[400]); D[500] = hex2rgb(base[500]);
  D[600] = hex2rgb(base[400]); D[700] = hex2rgb(base[300]); D[800] = hex2rgb(base[200]); D[900] = hex2rgb(base[100]);
  scales[n] = { light: L, dark: D };
}
{ const L = {}, D = {}; for (const s of SHADES) L[s] = hex2rgb(royalIndigo[s]);
  const gb = hex2rgb(royalIndigo[500]); for (const [s, a] of [[50, 0.1], [100, 0.16], [200, 0.26], [300, 0.4]]) D[s] = blend(gb, surfDark, a);
  for (const s of [400, 500, 600, 700, 800, 900]) D[s] = hex2rgb(royalIndigoDark[s]); scales.brand = { light: L, dark: D }; }
{ const L = {}, D = {}; for (const s of [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]) { L[s] = hex2rgb(colors.slate[s]); D[s] = hex2rgb(slateDark[s]); } scales.slate = { light: L, dark: D }; }

// the stock slate-500/400 are just under the contrast minimum on the warm off-white canvas: nudge them
scales.slate.light[500] = hex2rgb("#586377"); scales.slate.light[400] = hex2rgb("#7B8798");
const trip = (c) => c.map((v) => Math.round(v)).join(" ");
const block = (mode) => {
  let o = "";
  for (const [k, v] of Object.entries(S[mode])) o += `  --${k}: ${trip(hex2rgb(v))};\n`;
  for (const [n, sc] of Object.entries(scales)) for (const [s, c] of Object.entries(sc[mode])) o += `  --${n}-${s}: ${trip(c)};\n`;
  return o;
};
const css = `/* GENERATED by scripts/gen-theme.mjs - do not edit by hand. RGB triplets so Tailwind can apply opacity (rgb(var(--x) / <alpha>)). */
:root, :root[data-theme="light"] {\n  color-scheme: light;\n${block("light")}}
:root[data-theme="dark"] {\n  color-scheme: dark;\n${block("dark")}}
`;
writeFileSync(new URL("../app/theme.css", import.meta.url), css);

// ---- contrast gate: pairs the UI actually renders (text, background, minimum ratio)
const get = (mode, name) => { if (S[mode][name]) return hex2rgb(S[mode][name]); const [n, s] = name.split("-"); return scales[n][mode][s]; };
const pairs = [
  ["slate-900", "surface", 7], ["slate-700", "surface", 7], ["slate-600", "surface", 4.5], ["slate-500", "surface", 4.5], ["slate-500", "canvas", 4.5], ["slate-400", "surface", 3],
  ["emerald-600", "surface", 4.5], ["rose-600", "surface", 4.5], ["amber-600", "surface", 4.5], ["sky-600", "surface", 4.5], ["violet-600", "surface", 4.5], ["brand-700", "surface", 4.5], ["brand-600", "surface", 4.5],
  ["emerald-700", "emerald-50", 4.5], ["rose-700", "rose-50", 4.5], ["amber-700", "amber-50", 4.5], ["orange-700", "orange-50", 4.5], ["brand-700", "brand-50", 4.5], ["amber-900", "amber-50", 4.5],
  ["accent-fg", "accent", 4.5], ["slate-500", "slate-50", 4.5], ["slate-700", "slate-100", 4.5],
];
let bad = 0;
for (const mode of ["light", "dark"]) for (const [fg, bg, min] of pairs) {
  const r = contrast(get(mode, fg), get(mode, bg));
  if (r < min) { bad++; console.log(`LOW  ${mode.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)} (< ${min})`); }
}
console.log(bad ? `${bad} contrast pair(s) below minimum` : `all ${pairs.length * 2} contrast checks pass (${pairs.length} pairs x 2 themes)`);
process.exit(bad ? 1 : 0);
